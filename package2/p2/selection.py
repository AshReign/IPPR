"""Deterministic P2 selection from complete externally computed P5 scores.

This module does not compute any metric or implement P5 matching/filtering.
"""
from __future__ import annotations
from decimal import Decimal, InvalidOperation
import re

THRESHOLDS = tuple(Decimal(i) / 100 for i in range(10, 91, 5))


def require(condition, message):
    if not condition:
        raise ValueError(message)


def decimal(value):
    require(not isinstance(value, bool), 'Boolean is not a numeric score')
    try:
        result = Decimal(str(value))
    except (InvalidOperation, ValueError) as error:
        raise ValueError(f'Invalid numeric value {value!r}') from error
    require(result.is_finite(), 'Nonfinite score/threshold')
    return result


def digest(value):
    return isinstance(value, str) and re.fullmatch(r'[0-9a-f]{64}', value) is not None


def select(scores, checkpoint_manifest, protocol_sha256):
    """Validate the entire search matrix and return one winner without freezing it.

    checkpoint_manifest must come from a completed formal run. Scores must be
    generated by a supplied P5 evaluator and the agreed output adapter, not by
    this module or native Ultralytics mAP fitness.
    """
    require(checkpoint_manifest.get('status') == 'completed_formal_run', 'Formal run is not complete')
    require(scores.get('schema') == 'p2-p5-dev-scores-v1', 'Unexpected score schema')
    require(scores.get('status') == 'complete' and scores.get('split') == 'dev', 'Need complete dev scores')
    require(digest(protocol_sha256) and scores.get('selection_protocol_sha256') == protocol_sha256,
            'Scores use a different predeclared selection protocol')
    for field in ('evaluator_source_sha256', 'output_adapter_sha256', 'prediction_config_sha256',
                  'dev_manifest_sha256', 'reuse_equivalence_report_sha256'):
        require(digest(scores.get(field)), f'Missing valid provenance: {field}')
    require(scores['dev_manifest_sha256'] == checkpoint_manifest.get('dev_manifest_sha256'),
            'Score split differs from the formal-run dev manifest')
    require(scores.get('p1_commit') == checkpoint_manifest.get('p1_commit'), 'P1 commit differs')
    require(scores.get('metric_source') == 'P5', 'Only actual P5 metrics may select the model')
    candidates = checkpoint_manifest.get('checkpoints', [])
    require(bool(candidates), 'No checkpoint candidates')
    expected = {}
    epochs = set()
    for item in candidates:
        sha = item.get('sha256')
        epoch = item.get('completed_epoch')
        require(digest(sha), 'Invalid checkpoint SHA256')
        require(type(epoch) is int and 1 <= epoch <= 30 and epoch not in epochs, 'Invalid/repeated epoch')
        require(sha not in expected, 'Repeated checkpoint file hash')
        expected[sha] = epoch
        epochs.add(epoch)
    require(epochs == set(range(1, max(epochs) + 1)), 'Every completed epoch must be included')
    require(max(epochs) == checkpoint_manifest.get('actual_epochs'), 'Incomplete checkpoint inventory')
    seen = set()
    parsed = []
    for row in scores.get('rows', []):
        sha = row.get('checkpoint_sha256')
        epoch = row.get('completed_epoch')
        require(sha in expected and type(epoch) is int and epoch == expected[sha], 'Checkpoint/epoch mismatch')
        threshold = decimal(row.get('threshold'))
        require(threshold in THRESHOLDS, 'Threshold outside the 17-point grid')
        key = (sha, threshold)
        require(key not in seen, 'Duplicate checkpoint/threshold score')
        seen.add(key)
        require(row.get('status') == 'complete', 'Failed or partial scoring row')
        metrics = {name: decimal(row.get(name)) for name in ('f2', 'recall', 'precision')}
        require(all(Decimal(0) <= value <= Decimal(1) for value in metrics.values()), 'Metric outside [0,1]')
        parsed.append(((-metrics['f2'], -metrics['recall'], -metrics['precision'], epoch, threshold), row))
    require(seen == {(sha, threshold) for sha in expected for threshold in THRESHOLDS},
            'Search matrix must include every saved epoch and all 17 thresholds')
    winner = min(parsed, key=lambda item: item[0])[1]
    return {'status': 'selected_from_P5_dev_scores_not_yet_frozen', 'winner': winner,
            'completed_epochs_scored': len(expected), 'scoring_combinations': len(parsed),
            'selection_protocol_sha256': protocol_sha256,
            'ranking': ['f2 descending', 'recall descending', 'precision descending',
                        'completed_epoch ascending', 'threshold ascending'],
            'remaining_freeze_gates': ['validate selected checkpoint soft masks and cache restoration',
                                       'record approved output adapter and inference/transform versions',
                                       'write immutable final freeze artifact before final-val export']}
